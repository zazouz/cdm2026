export function translateTeam(name: string, lang: Lang): string {
  if (lang === 'en') return name
  return TEAM_FR[name] ?? name
}

export function stageLabel(stage: string, lang: Lang): string {
  return STAGE_LABELS[stage]?.[lang] ?? stage
}
